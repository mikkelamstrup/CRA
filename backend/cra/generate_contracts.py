def ts_type(schema: dict[str, Any]) -> str:
    if "$ref" in schema:
        return str(schema["$ref"]).rsplit("/", 1)[1]
    if "const" in schema:
        return json.dumps(schema["const"])
    if "enum" in schema:
        return " | ".join(json.dumps(v) for v in schema["enum"])
    for union in ("anyOf", "oneOf"):
        if union in schema:
            return " | ".join(ts_type(item) for item in schema[union])
    kind = schema.get("type")
    if kind in ("string", "boolean", "null"):
        return str(kind)
    if kind in ("number", "integer"):
        return "number"
    if kind == "array":
        return f"Array<{ts_type(schema['items'])}>"
    if kind == "object":
        fields = []
        for name, field in schema.get("properties", {}).items():
            optional = "" if name in schema.get("required", []) else "?"
            fields.append(f"  {json.dumps(name)}{optional}: {ts_type(field)};")
        if schema.get("additionalProperties") not in (None, False):
            raise ValueError("Unbounded object contracts are unsupported")
        return "{\n" + "\n".join(fields) + "\n}"
    raise ValueError(f"Unsupported contract schema type: {kind}")


def generated() -> tuple[str, str]:
    schemas = {model.__name__: model.model_json_schema() for model in MODELS}
    definitions: dict[str, dict[str, Any]] = {}
    for name, schema in schemas.items():
        for key, value in {**schema.get("$defs", {}), name: schema}.items():
            if key in definitions and definitions[key] != value:
                raise ValueError("Conflicting schema definition")
            definitions[key] = value
    types = "// Generated by python -m cra.generate_contracts; do not edit.\n"
    for name, schema in sorted(definitions.items()):
        types += f"export type {name} = {ts_type(schema)};\n\n"
    return types.rstrip() + "\n", json.dumps(
        schemas, indent=2, sort_keys=True, ensure_ascii=False
    ) + "\n"


if __name__ == "__main__":
    types, schemas = generated()
    (ROOT / "frontend/src/contracts.ts").write_text(types)
    (ROOT / "content/contracts.v1.json").write_text(schemas)
    print("Contract artifacts generated")
